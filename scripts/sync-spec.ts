// Generates pages from the spec submodule, so module rules and Public API tables are never
// copied by hand:
//   src/content/docs/docs/<module>/rules.md   rules, sources and recorded decisions
//   src/generated/api/<module>.json           rows of the module's Public API table
// Runs before `astro dev`, `astro build` and `astro check`; the output is gitignored.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MODULES_DIR = join(ROOT, 'spec', 'modules');
const RULES_DIR = join(ROOT, 'src', 'content', 'docs', 'docs');
const API_DIR = join(ROOT, 'src', 'generated', 'api');
const SPEC_VERSION = readFileSync(join(ROOT, 'spec', 'VERSION'), 'utf8').trim();
const SPEC_URL = 'https://github.com/mdgascar/mdg-utils-spec/blob/dev/modules';

interface Section {
  readonly heading: string;
  readonly body: string;
}

interface ModuleReadme {
  readonly title: string;
  readonly intro: string;
  readonly sections: readonly Section[];
}

function parseReadme(markdown: string): ModuleReadme {
  const [head = '', ...parts] = markdown.split(/^## /m);
  const titleLine = /^# .+?(?: —|:) (.+)$/m.exec(head);
  if (titleLine?.[1] === undefined) throw new Error('Module README has no "# name: Title" line.');
  const intro = head.replace(/^# .+$/m, '').trim();
  const sections = parts.map((part) => {
    const newline = part.indexOf('\n');
    return { heading: part.slice(0, newline).trim(), body: part.slice(newline + 1).trim() };
  });
  return { title: titleLine[1], intro, sections };
}

function yamlString(value: string): string {
  return JSON.stringify(value.replace(/\s+/g, ' ').replace(/[*`]/g, ''));
}

function rulesPage(module: string, readme: ModuleReadme): string {
  const body = readme.sections
    .filter((section) => section.heading !== 'Public API')
    .map((section) => `## ${section.heading}\n\n${section.body}`)
    .join('\n\n');
  return `---
title: ${yamlString(`${readme.title}: rules and sources`)}
description: ${yamlString(readme.intro)}
kicker: Spec ${SPEC_VERSION}
editUrl: ${SPEC_URL}/${module}/README.md
---

<!-- GENERATED by scripts/sync-spec.ts from spec/modules/${module}/README.md. Edit the spec instead. -->

${body}
`;
}

interface ApiRow {
  readonly name: string;
  readonly does: string;
  readonly js: string;
  readonly php: string;
}

/** Rows of the module's Public API table: | Function | Does | JavaScript | PHP |. */
function apiRows(readme: ModuleReadme): ApiRow[] {
  const section = readme.sections.find((candidate) => candidate.heading === 'Public API');
  if (section === undefined) throw new Error(`"${readme.title}" has no Public API section.`);
  const lines = section.body.split('\n').filter((line) => line.startsWith('|'));
  return lines.slice(2).map((line) => {
    const [name = '', does = '', js = '', php = ''] = line
      .slice(1, -1)
      .split('|')
      .map((cell) => cell.trim());
    return { name, does, js, php };
  });
}

rmSync(API_DIR, { recursive: true, force: true });
mkdirSync(API_DIR, { recursive: true });
const modules = readdirSync(MODULES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
for (const module of modules) {
  const readme = parseReadme(readFileSync(join(MODULES_DIR, module, 'README.md'), 'utf8'));
  mkdirSync(join(RULES_DIR, module), { recursive: true });
  writeFileSync(join(RULES_DIR, module, 'rules.md'), rulesPage(module, readme));
  writeFileSync(join(API_DIR, `${module}.json`), `${JSON.stringify(apiRows(readme), null, 2)}\n`);
}
console.log(
  `Generated rules pages and API tables for: ${modules.join(', ')} (spec ${SPEC_VERSION})`,
);
